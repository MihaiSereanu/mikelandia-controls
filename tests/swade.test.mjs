test("SWADE has one Conviction card with native Spend/End and separate Basic Actions", async t => {
  const f = setup(t);
  const conviction = () => f.view().panels.find(tab => tab.id === "main").sections.filter(section => section.id.startsWith("conviction"));
  assert.equal(conviction().length, 1);
  assert.equal(conviction()[0].rows[0].secondaryAction.label, "Spend Conviction");
  assert.equal(conviction()[0].rows[0].secondaryAction.icon, "fa-dice");
  await f.action("conviction");
  assert.equal(f.actor.system.details.conviction.value, 0);
  assert.equal(f.actor.system.details.conviction.active, true);
  assert.equal(conviction()[0].rows[0].secondaryAction.label, "End Conviction");
  await f.action("conviction");
  assert.equal(f.actor.system.details.conviction.value, 0);
  assert.equal(f.actor.system.details.conviction.active, false);
  assert.equal(conviction()[0].rows[0].secondaryAction, undefined);
  assert.equal(f.gateway.capabilitiesForActor(f.actor).profileActions.some(action => action.id === "conviction"), false);
  const abilities = f.view().panels.find(tab => tab.id === "abilities");
  assert.deepEqual(abilities.sections.find(section => section.id === "basic-actions").rows.map(row => row.id), ["defend"]);
  assert.deepEqual(abilities.sections.find(section => section.id === "abilities").rows.map(row => row.id), ["special"]);
  assert.deepEqual(abilities.sections.find(section => section.id === "ancestry").rows.map(row => row.id), ["ancestry"]);
  assert.equal(f.view().panels.find(tab => tab.id === "combat").sections.find(section => section.id === "item-actions").layout, "actions");
  assert.equal(f.view().panels.find(tab => tab.id === "effects").sections[0].rows[0].editControl, "checkbox");
});
test("SWADE edits native resources and equipment with fresh permissions and revisions", async t => {
  const f = setup(t);
  await f.gateway.execute(ACTOR_COMMANDS.EDIT_PROFILE_RESOURCE, f.editPayload("wounds", 1));
  await f.gateway.execute(ACTOR_COMMANDS.EDIT_PROFILE_RESOURCE, f.editPayload("bennies", 2));
  assert.deepEqual(f.calls.at(-1), ["spendBenny"]);
  await f.gateway.execute(ACTOR_COMMANDS.EDIT_PROFILE_RESOURCE, f.editPayload("equipped:sword", 2));
  assert.equal(f.actor.items.get("sword").system.equipStatus, 2);
  await f.gateway.execute(ACTOR_COMMANDS.EDIT_PROFILE_RESOURCE, f.editPayload("equipped:sword", 5));
  assert.equal(f.actor.items.get("sword").system.equipStatus, 5);
  await f.gateway.execute(ACTOR_COMMANDS.EDIT_PROFILE_RESOURCE, f.editPayload("quantity:ration", 0));
  await f.gateway.execute(ACTOR_COMMANDS.EDIT_PROFILE_RESOURCE, f.editPayload("currency", 12.25));
  assert.equal(f.actor.system.details.currency, 12.25);
  await f.gateway.execute(ACTOR_COMMANDS.EDIT_PROFILE_RESOURCE, f.editPayload("power-points-1", 4));
  assert.equal(f.actor.system.powerPoints["Weird Science"].value, 4);
  await assert.rejects(f.gateway.execute(ACTOR_COMMANDS.EDIT_PROFILE_RESOURCE, f.editPayload("currency", NaN)), { code: "INVALID_INPUT" });
  assert.equal(f.actor.items.get("ration").system.quantity, 0);
  const stale = f.editPayload("wounds", 2); await f.actor.update({ "system.wounds.value": 0 });
  await assert.rejects(f.gateway.execute(ACTOR_COMMANDS.EDIT_PROFILE_RESOURCE, stale), { code: "STALE_STATE" });
  await assert.rejects(f.gateway.execute(ACTOR_COMMANDS.EDIT_PROFILE_RESOURCE, f.editPayload("equipped:sword", 6)), { code: "INVALID_INPUT" });
  const denied = f.editPayload("wounds", 2); f.actor.testUserPermission = () => false;
  await assert.rejects(f.gateway.execute(ACTOR_COMMANDS.EDIT_PROFILE_RESOURCE, denied));
});
test("SWADE wounds increase damage; enemy health never exposes counts", async t => {
  const f = setup(t), scope = createTaskScope(); t.after(() => scope.dispose());
  const hits = [];
  createFoundryDamageGateway().watch(scope, { getSource: () => f.actor.uuid, isActive: () => true, onDamage: hit => hits.push(hit), onReset() {} });
  await f.actor.update({ "system.wounds.value": 2 }); await f.actor.update({ "system.wounds.max": 4 }); await f.actor.update({ "system.wounds.value": 1 });
  assert.deepEqual(hits, [{ amount: 2, noun: "wounds", down: false }]);
  assert.deepEqual(projectCombatHealth(f.integration, { disposition: -1, actor: f.actor }), { status: "Wounded" });
  assert.equal(projectCombatHealth(f.integration, { disposition: 1, actor: f.actor }).value, 1);
  assert.equal(f.integration.initiativeLabel({ system: { cardString: "Ace of Spades", roundHeld: true } }), "Ace of Spades · Hold");
  f.game.combat = { id: "fight", turns: [{ id: "held", initiative: 2, system: { cardString: "Ace of Spades", roundHeld: true } },
    { id: "joker", initiative: 54, system: { cardString: "Joker" } }] };
  const rows = createFoundryCombatGateway().snapshot().combatants;
  assert.deepEqual(rows.map(row => [row.id, row.initiativeLabel]), [["held", "Ace of Spades · Hold"], ["joker", "Joker"]]);
  scope.dispose();
});
