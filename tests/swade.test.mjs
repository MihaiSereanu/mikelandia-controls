  const custom = rows().find(row => row.id === "custom");
  assert.equal(custom.tooltip, undefined); assert.equal(custom.editControl, "checkbox");
  f.settings.set("wealthType", "currency");
  assert.equal(f.view().panels.find(tab => tab.id === "inventory").sections.some(section => section.id === "wealth"), false);
